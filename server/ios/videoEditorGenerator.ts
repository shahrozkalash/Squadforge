/**
 * Phase 35 — Native iOS Video Editor generator ("ClipForge").
 *
 * Generates a genuine, native Xcode project (Swift + SwiftUI)
 * implementing the SquadForge video editor on device: PhotosPicker
 * media import, a multitrack timeline with the same project model
 * and edit operations as the server engine (Phases 20/26–31),
 * AVFoundation preview (AVPlayer over an AVMutableComposition),
 * AVAssetExportSession export with progress and cancellation,
 * on-device project persistence with recovery, and an optional
 * connection to the SquadForge video-editor API (Phase 31 project
 * load/save).
 *
 * It builds on the Phase 25 generator: the base project comes from
 * IosProjectGenerator, then the starter app's content files are
 * replaced by the editor sources. One iOS-specific subtlety the
 * Android generator never faces: an Xcode project lists every
 * source file explicitly in project.pbxproj, so the editor's files
 * are patched into the pbxproj (new Editor/Player/Export/UI groups,
 * starter Views/Components/Models/ViewModels groups removed) using
 * the Phase 25 generator's own deterministic object-id scheme
 * (sha256 of `squadforge-ios:<label>`). Every patch is anchored on
 * exact emitted text and throws if the anchor is missing, so
 * generator drift fails loudly instead of emitting a corrupt
 * project. No WebView is involved anywhere.
 *
 * Frameworks (all Apple system frameworks — no third-party code):
 * - AVFoundation / AVKit — composition, playback and export.
 * - PhotosUI — the system media picker (PHPicker); the app never
 *   reads the photo library directly.
 * - SwiftUI — the editor UI.
 */
import { createHash } from 'crypto';
import { IosProjectGenerator } from './iosProjectGenerator.js';
import { IosProjectConfig } from './types.js';

export function getVideoEditorConfig(
  appName: string = 'ClipForge',
  bundleId: string = 'com.squadforge.clipforge'
): IosProjectConfig {
  const base = IosProjectGenerator.getDefaultConfig(appName, bundleId);
  return {
    ...base,
    // Import goes through the system PhotosPicker, which grants
    // access to exactly what the user picks; the app itself never
    // reads the photo library. The photoLibrary permission is the
    // one the Phase 25 generator models for picker-based apps, and
    // it puts the standard NSPhotoLibraryUsageDescription into
    // Info.plist. Network access for the optional SquadForge API
    // connection needs no permission on iOS.
    permissions: ['photoLibrary']
  };
}

