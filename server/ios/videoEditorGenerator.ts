/**
 * Generate the complete ClipForge iOS project: the Phase 25 base
 * project with the editor sources and a pbxproj that references
 * them.
 */
export function generateVideoEditorProject(
  config: IosProjectConfig = getVideoEditorConfig()
): Record<string, string> {
  const files = IosProjectGenerator.generateProjectFiles(config);
  const m = config.moduleName;

  // Replace the starter app entry and root view with the editor's.
  files[`${m}/${m}App.swift`] = appSwift(config);
  files[`${m}/ContentView.swift`] = contentViewSwift(config);

  // Remove the starter content the editor replaces.
  for (const rel of STARTER_SWIFT_FILES) {
    delete files[`${m}/${rel}`];
  }

  // The editor sources.
  files[`${m}/Editor/EditorModels.swift`] = editorModelsSwift();
  files[`${m}/Editor/EditorOps.swift`] = editorOpsSwift();
  files[`${m}/Editor/ProjectStore.swift`] = projectStoreSwift();
  files[`${m}/Editor/SquadForgeApi.swift`] = squadForgeApiSwift();
  files[`${m}/Player/PreviewPlayer.swift`] = previewPlayerSwift();
  files[`${m}/Export/VideoExporter.swift`] = videoExporterSwift();
  files[`${m}/UI/EditorViewModel.swift`] = editorViewModelSwift();
  files[`${m}/UI/EditorView.swift`] = editorViewSwift();

  // The pbxproj must reference exactly the Swift files above.
  const pbxKey = `${m}.xcodeproj/project.pbxproj`;
  if (!files[pbxKey]) throw new Error('Phase 25 base project has no project.pbxproj to patch');
  files[pbxKey] = patchPbxproj(files[pbxKey]);

  files['README.md'] = `# ${config.appName} (iOS)\n\nGenerated by SquadForge Phase 35 (Native iOS Video Editor) on top\nof the Phase 25 iOS engine. See \`VIDEO_EDITOR_README.md\` for the\neditor's structure, behaviour and stated limitations.\n`;
  files['VIDEO_EDITOR_README.md'] = videoEditorReadme(config);
  return files;
}

function videoEditorReadme(config: IosProjectConfig): string {
  return `# ClipForge — Native iOS Video Editor (Phase 35)

Generated by SquadForge's Phase 35 generator on top of the Phase 25
iOS engine. Bundle ID: ${config.bundleId}.

## What it is
A genuine native editor: Swift + SwiftUI UI, AVFoundation preview
(AVPlayer over an AVMutableComposition built from the timeline),
AVAssetExportSession export. No WebView.

- Import: the system PhotosPicker (video/image) and the document
  picker (audio). Picked media is copied into the app's own
  Documents/media folder, so the app works entirely inside its
  sandbox — no photo-library access by the app itself, no
  security-scoped bookmarks to maintain. The project stores media
  paths relative to Documents and re-resolves them by file name if
  the container path changes.
- Editing: multitrack timeline (video + audio tracks) with the same
  project model and operations as the SquadForge server engine —
  add/trim/split/move/remove clips, volume, speed, text overlays,
  captions, track gain/mute.
- Preview: AVPlayer plays a composition built from the timeline —
  the base video track's clips at their timeline positions, plus
  the first audio track — with per-clip volume steps in an audio
  mix. Text overlays and the active caption render natively in
  SwiftUI over the player.
- Export: AVAssetExportSession renders the base video track plus
  every unmuted audio track to MP4 at Source/480p/720p/1080p (a
  video composition scales to the target size), with real progress
  (the session's own progress value, polled) and cancellation
  (cancelExport(); the partial file is deleted). A sidecar .srt
  with the project's captions is written next to the MP4. Export
  notes in the app state what was not included.
- Projects: saved as JSON in the app's Documents after every edit
  and reopened on launch (recovery). Optionally load/save the
  server project through the SquadForge video-editor API
  (Phase 31 endpoints) using your own session cookie; the client
  translates between the app's project JSON and the server's
  SerializedVideoProject envelope.

## Known limitations (stated, not hidden)
- Overlay (PiP) video tracks are preview-only; the app export
  carries the base video track. Use the server export for PiP
  compositing.
- Transitions render as cuts in the app export.
- Clip speed and audio fades are honoured in editing/preview math,
  not baked into the app export.
- Text overlays render in preview but are not burned into the app
  export; the server export burns them in.
- Image clips are editable in the timeline, but the app preview
  and export skip them (the compositions are built from audio/
  video tracks); the server export loops stills.
- Preview mixes only the first audio track; export mixes every
  unmuted audio track.
- Projects loaded from the server reference server-side media
  paths; the media itself must be imported on the device before
  those clips can play or export.
- Timeline clip movement is button-driven (±0.5 s), not drag.

## Frameworks
AVFoundation, AVKit, PhotosUI, SwiftUI, Foundation — all Apple
system frameworks; there are no third-party dependencies and no
licenses to attribute.
`;
}

