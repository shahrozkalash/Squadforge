/** The Phase 25 generator's deterministic object-id scheme. */
function pid(label: string): string {
  return createHash('sha256').update(`squadforge-ios:${label}`).digest('hex').slice(0, 24).toUpperCase();
}

function fileName(rel: string): string {
  return rel.split('/').pop()!;
}

function buildFileLine(rel: string): string {
  return `\t\t${pid(`build:${rel}`)} /* ${fileName(rel)} in Sources */ = {isa = PBXBuildFile; fileRef = ${pid(`ref:${rel}`)} /* ${fileName(rel)} */; };`;
}

function fileRefLine(rel: string): string {
  return `\t\t${pid(`ref:${rel}`)} /* ${fileName(rel)} */ = {isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = ${fileName(rel)}; sourceTree = "<group>"; };`;
}

function sourcesLine(rel: string): string {
  return `\t\t\t\t${pid(`build:${rel}`)} /* ${fileName(rel)} in Sources */,`;
}

function groupBlock(id: string, name: string, childRefs: string[]): string {
  return [
    `\t\t${id} = {`,
    '\t\t\tisa = PBXGroup;',
    '\t\t\tchildren = (',
    ...childRefs.map((c) => `\t\t\t\t${c},`),
    '\t\t\t);',
    `\t\t\tname = ${name};`,
    `\t\t\tpath = ${name};`,
    '\t\t\tsourceTree = "<group>";',
    '\t\t};'
  ].join('\n');
}

function patchPbxproj(pbx: string): string {
  const mustReplace = (from: string, to: string, what: string): void => {
    if (!pbx.includes(from)) {
      throw new Error(`Phase 25 pbxproj anchor not found (${what}); generator drift must be fixed before patching`);
    }
    pbx = pbx.replace(from, to);
  };
  const mustRemoveLine = (line: string, what: string): void => mustReplace(`${line}\n`, '', what);

  // 1. Drop the starter files from PBXBuildFile, PBXFileReference
  //    and the Sources build phase.
  for (const rel of STARTER_SWIFT_FILES) {
    mustRemoveLine(buildFileLine(rel), `build file ${rel}`);
    mustRemoveLine(fileRefLine(rel), `file reference ${rel}`);
    mustRemoveLine(sourcesLine(rel), `sources entry ${rel}`);
  }

  // 2. Add the editor files right after ContentView's entries.
  mustReplace(
    buildFileLine('ContentView.swift'),
    [buildFileLine('ContentView.swift'), ...EDITOR_SWIFT_FILES.map(buildFileLine)].join('\n'),
    'build file insertion point'
  );
  mustReplace(
    fileRefLine('ContentView.swift'),
    [fileRefLine('ContentView.swift'), ...EDITOR_SWIFT_FILES.map(fileRefLine)].join('\n'),
    'file reference insertion point'
  );
  mustReplace(
    sourcesLine('ContentView.swift'),
    [sourcesLine('ContentView.swift'), ...EDITOR_SWIFT_FILES.map(sourcesLine)].join('\n'),
    'sources insertion point'
  );

  // 3. Module group: swap the four starter groups for the editor's.
  const oldChildren = [
    `\t\t\t\t${pid('group:Views')} /* Views */,`,
    `\t\t\t\t${pid('group:Components')} /* Components */,`,
    `\t\t\t\t${pid('group:Models')} /* Models */,`,
    `\t\t\t\t${pid('group:ViewModels')} /* ViewModels */,`
  ].join('\n');
  const newChildren = [
    `\t\t\t\t${pid('group:Editor')} /* Editor */,`,
    `\t\t\t\t${pid('group:Player')} /* Player */,`,
    `\t\t\t\t${pid('group:Export')} /* Export */,`,
    `\t\t\t\t${pid('group:UI')} /* UI */,`
  ].join('\n');
  mustReplace(oldChildren, newChildren, 'module group children');

  // 4. Replace the starter group blocks with the editor group blocks.
  const ref = (rel: string): string => `${pid(`ref:${rel}`)} /* ${fileName(rel)} */`;
  mustReplace(
    groupBlock(pid('group:Views'), 'Views', [ref('Views/ItemDetailView.swift')]),
    groupBlock(pid('group:Editor'), 'Editor', [
      ref('Editor/EditorModels.swift'),
      ref('Editor/EditorOps.swift'),
      ref('Editor/ProjectStore.swift'),
      ref('Editor/SquadForgeApi.swift')
    ]),
    'Views group block'
  );
  mustReplace(
    groupBlock(pid('group:Components'), 'Components', [ref('Components/ItemRowView.swift')]),
    groupBlock(pid('group:Player'), 'Player', [ref('Player/PreviewPlayer.swift')]),
    'Components group block'
  );
  mustReplace(
    groupBlock(pid('group:Models'), 'Models', [ref('Models/Item.swift')]),
    groupBlock(pid('group:Export'), 'Export', [ref('Export/VideoExporter.swift')]),
    'Models group block'
  );
  mustReplace(
    groupBlock(pid('group:ViewModels'), 'ViewModels', [ref('ViewModels/ItemListViewModel.swift')]),
    groupBlock(pid('group:UI'), 'UI', [ref('UI/EditorViewModel.swift'), ref('UI/EditorView.swift')]),
    'ViewModels group block'
  );

  return pbx;
}

