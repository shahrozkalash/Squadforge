  public static getDefaultConfig(
    appName: string = 'SquadForgeApp',
    assemblyName?: string
  ): DesktopProjectConfig {
    const asm = (assemblyName || appName).replace(/[^a-zA-Z0-9_]/g, '');
    return {
      appName,
      assemblyName: asm || 'SquadForgeApp',
      platform: 'windows',
      uiFramework: 'winforms',
      targetFramework: 'net8.0-windows',
      dotnetSdkVersion: '8.0',
      version: '1.0.0',
      company: 'SquadForge',
      description: `${appName} — generated by SquadForge`,
      requireAdministrator: false
    };
  }

  /** Default config for the Linux target (Phase 36): .NET 8 + Avalonia UI. */
  public static getLinuxDefaultConfig(
    appName: string = 'SquadForgeApp',
    assemblyName?: string
  ): DesktopProjectConfig {
    const base = DesktopProjectGenerator.getDefaultConfig(appName, assemblyName);
    return {
      ...base,
      platform: 'linux',
      uiFramework: 'avalonia',
      targetFramework: 'net8.0',
      requireAdministrator: false
    };
  }

  /** Assembly names must be valid C# namespace roots. */
  public static validateConfig(config: DesktopProjectConfig): string[] {
    const errors: string[] = [];
    if (!config.appName || !config.appName.trim()) errors.push('appName is required');
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(config.assemblyName || '')) {
      errors.push('assemblyName must start with a letter or underscore and contain only letters, digits, underscores');
    }
    if (config.platform === 'windows') {
      if (!/^net8\.0-windows$/.test(config.targetFramework || '')) {
        errors.push('targetFramework must be net8.0-windows for the Windows desktop engine');
      }
      if (config.uiFramework !== 'winforms' && config.uiFramework !== 'wpf') {
        errors.push('uiFramework must be winforms or wpf for the Windows desktop engine');
      }
    } else if (config.platform === 'linux') {
      if (!/^net8\.0$/.test(config.targetFramework || '')) {
        errors.push('targetFramework must be net8.0 for the Linux desktop engine');
      }
      if (config.uiFramework !== 'avalonia') {
        errors.push('uiFramework must be avalonia for the Linux desktop engine (WinForms and WPF are Windows-only)');
      }
      if (config.requireAdministrator) {
        errors.push('requireAdministrator has no Linux equivalent in this engine; leave it false for Linux projects');
      }
    } else {
      errors.push(`platform '${config.platform}' is not yet supported (supported platforms: windows, linux)`);
    }
    return errors;
  }

  /**
   * Detects a .NET SDK (8+) on this host without hardcoded paths:
   * DOTNET_ROOT, PATH lookup, then standard install locations.
   * Returns the dotnet executable path or null.
   */
  public static detectDotnet(): string | null {
    const exe = process.platform === 'win32' ? 'dotnet.exe' : 'dotnet';
    const candidates: string[] = [];
    if (process.env.DOTNET_ROOT) candidates.push(path.join(process.env.DOTNET_ROOT, exe));
    try {
      const out = execFileSync(process.platform === 'win32' ? 'where' : 'which', ['dotnet'], {
        encoding: 'utf-8',
        timeout: 3000
      }).trim();
      if (out) candidates.push(out.split('\n')[0].trim());
    } catch {
      // not on PATH
    }
    if (process.platform === 'win32') {
      if (process.env.ProgramFiles) candidates.push(path.join(process.env.ProgramFiles, 'dotnet', exe));
    } else {
      candidates.push('/usr/share/dotnet/dotnet', '/usr/lib/dotnet/dotnet', '/usr/local/share/dotnet/dotnet');
      if (process.env.HOME) candidates.push(path.join(process.env.HOME, '.dotnet', exe));
    }
    for (const c of candidates) {
      if (c && fs.existsSync(c)) return c;
    }
    return null;
  }

  /** Returns installed SDK versions (e.g. ['8.0.100']) or [] when none. */
  public static listSdks(dotnetExe: string): string[] {
    try {
      const out = execFileSync(dotnetExe, ['--list-sdks'], { encoding: 'utf-8', timeout: 15000 });
      return out
        .split('\n')
        .map((l) => l.trim().split(' ')[0])
        .filter((v) => /^\d+\.\d+\.\d+/.test(v));
    } catch {
      return [];
    }
  }

