import * as fs from 'fs';
import * as path from 'path';
import { execFileSync } from 'child_process';
import type { DesktopProjectConfig } from './types.js';

/**
 * Phase 18: generates real, buildable Windows desktop projects
 * (C# / .NET 8 / WinForms). The generated source is a genuine
 * application — Program entry point, main form, state persistence —
 * never a mockup. Linux/macOS configs are rejected honestly until
 * their generators land; the platform field keeps the door open.
 */
export class DesktopProjectGenerator {
  public static getDefaultConfig(
    appName: string = 'SquadForgeApp',
    assemblyName?: string
  ): DesktopProjectConfig {
    const asm = (assemblyName || appName).replace(/[^a-zA-Z0-9_]/g, '');
    return {
      appName,
      assemblyName: asm || 'SquadForgeApp',
      platform: 'windows',
      uiFramework: 'winforms',
      targetFramework: 'net8.0-windows',
      dotnetSdkVersion: '8.0',
      version: '1.0.0',
      company: 'SquadForge',
      description: `${appName} — generated by SquadForge`,
      requireAdministrator: false
    };
  }

  /** Assembly names must be valid C# namespace roots. */
  public static validateConfig(config: DesktopProjectConfig): string[] {
    const errors: string[] = [];
    if (!config.appName || !config.appName.trim()) errors.push('appName is required');
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(config.assemblyName || '')) {
      errors.push('assemblyName must start with a letter or underscore and contain only letters, digits, underscores');
    }
    if (config.platform !== 'windows') {
      errors.push(`platform '${config.platform}' is not yet supported (Windows is the first target)`);
    }
    if (!/^net8\.0-windows$/.test(config.targetFramework || '')) {
      errors.push('targetFramework must be net8.0-windows for the Windows desktop engine');
    }
    if (config.uiFramework !== 'winforms' && config.uiFramework !== 'wpf') {
      errors.push('uiFramework must be winforms or wpf');
    }
    return errors;
  }

  /**
   * Detects a .NET SDK (8+) on this host without hardcoded paths:
   * DOTNET_ROOT, PATH lookup, then standard install locations.
   * Returns the dotnet executable path or null.
   */
  public static detectDotnet(): string | null {
    const exe = process.platform === 'win32' ? 'dotnet.exe' : 'dotnet';
    const candidates: string[] = [];
    if (process.env.DOTNET_ROOT) candidates.push(path.join(process.env.DOTNET_ROOT, exe));
    try {
      const out = execFileSync(process.platform === 'win32' ? 'where' : 'which', ['dotnet'], {
        encoding: 'utf-8',
        timeout: 3000
      }).trim();
      if (out) candidates.push(out.split('\n')[0].trim());
    } catch {
      // not on PATH
    }
    if (process.platform === 'win32') {
      if (process.env.ProgramFiles) candidates.push(path.join(process.env.ProgramFiles, 'dotnet', exe));
    } else {
      candidates.push('/usr/share/dotnet/dotnet', '/usr/lib/dotnet/dotnet', '/usr/local/share/dotnet/dotnet');
      if (process.env.HOME) candidates.push(path.join(process.env.HOME, '.dotnet', exe));
    }
    for (const c of candidates) {
      if (c && fs.existsSync(c)) return c;
    }
    return null;
  }

  /** Returns installed SDK versions (e.g. ['8.0.100']) or [] when none. */
  public static listSdks(dotnetExe: string): string[] {
    try {
      const out = execFileSync(dotnetExe, ['--list-sdks'], { encoding: 'utf-8', timeout: 15000 });
      return out
        .split('\n')
        .map((l) => l.trim().split(' ')[0])
        .filter((v) => /^\d+\.\d+\.\d+/.test(v));
    } catch {
      return [];
    }
  }

  public static generateProjectFiles(config: DesktopProjectConfig): Record<string, string> {
    const errors = DesktopProjectGenerator.validateConfig(config);
    if (errors.length > 0) {
      throw new Error(`Invalid desktop project config: ${errors.join('; ')}`);
    }
    const asm = config.assemblyName;
    const root = `src/${asm}`;
    const files: Record<string, string> = {};

    files[`${asm}.sln`] =
      `\r\nMicrosoft Visual Studio Solution File, Format Version 12.00\r\n` +
      `# Visual Studio Version 17\r\n` +
      `Project("{FAE04EC0-301F-11D3-BF4B-00C04F79EFBC}") = "${asm}", "src\\${asm}\\${asm}.csproj", "{B8E2A6A0-1A2B-4C3D-9E4F-5A6B7C8D9E0F}"\r\nEndProject\r\n` +
      `Global\r\n\tGlobalSection(SolutionConfigurationPlatforms) = preSolution\r\n\t\tDebug|Any CPU = Debug|Any CPU\r\n\t\tRelease|Any CPU = Release|Any CPU\r\n\tEndGlobalSection\r\nEndGlobal\r\n`;

    files[`${root}/${asm}.csproj`] =
      `<Project Sdk="Microsoft.NET.Sdk">\n\n` +
      `  <PropertyGroup>\n` +
      `    <OutputType>WinExe</OutputType>\n` +
      `    <TargetFramework>${config.targetFramework}</TargetFramework>\n` +
      `    <Nullable>enable</Nullable>\n` +
      `    <UseWindowsForms>true</UseWindowsForms>\n` +
      `    <ImplicitUsings>enable</ImplicitUsings>\n` +
      `    <AssemblyName>${asm}</AssemblyName>\n` +
      `    <!-- A Windows desktop app ships for the Windows x64 runtime; pinning the RID makes every host (incl. Linux CI) emit the real .exe apphost. -->\n` +
      `    <RuntimeIdentifier>win-x64</RuntimeIdentifier>\n` +
      `    <RootNamespace>${asm}</RootNamespace>\n` +
      `    <Version>${config.version}</Version>\n` +
      `    <Company>${config.company}</Company>\n` +
      `    <Description>${config.description}</Description>\n` +
      `    <ApplicationManifest>app.manifest</ApplicationManifest>\n` +
      `    <!-- Allow building the Windows target on non-Windows hosts (CI). -->\n` +
      `    <EnableWindowsTargeting>true</EnableWindowsTargeting>\n` +
      `  </PropertyGroup>\n\n` +
      `</Project>\n`;

    files[`${root}/app.manifest`] =
      `<?xml version="1.0" encoding="utf-8"?>\n` +
      `<assembly manifestVersion="1.0" xmlns="urn:schemas-microsoft-com:asm.v1">\n` +
      `  <assemblyIdentity version="1.0.0.0" name="${asm}"/>\n` +
      `  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v2">\n` +
      `    <security>\n` +
      `      <requestedPrivileges xmlns="urn:schemas-microsoft-com:asm.v3">\n` +
      `        <requestedExecutionLevel level="${config.requireAdministrator ? 'requireAdministrator' : 'asInvoker'}" uiAccess="false" />\n` +
      `      </requestedPrivileges>\n` +
      `    </security>\n` +
      `  </trustInfo>\n` +
      `  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">\n` +
      `    <application>\n` +
      `      <supportedOS Id="{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}" />\n` +
      `    </application>\n` +
      `  </compatibility>\n` +
      `</assembly>\n`;

    files[`${root}/Program.cs`] =
      `namespace ${asm};\n\n` +
      `static class Program\n` +
      `{\n` +
      `    /// <summary>The main entry point for the application.</summary>\n` +
      `    [STAThread]\n` +
      `    static void Main()\n` +
      `    {\n` +
      `        ApplicationConfiguration.Initialize();\n` +
      `        Application.Run(new MainForm());\n` +
      `    }\n` +
      `}\n`;

    files[`${root}/MainForm.cs`] =
      `using System.Text.Json;\n\n` +
      `namespace ${asm};\n\n` +
      `/// <summary>\n` +
      `/// Main window of ${config.appName}. Keeps a small persistent app state\n` +
      `/// (launch count, last message) in %AppData% to prove real file I/O,\n` +
      `/// state handling and a working event loop — a starting point the\n` +
      `/// owner extends, not a static mockup.\n` +
      `/// </summary>\n` +
      `public partial class MainForm : Form\n` +
      `{\n` +
      `    private readonly AppState _state;\n` +
      `    private readonly string _statePath;\n\n` +
      `    public MainForm()\n` +
      `    {\n` +
      `        InitializeComponent();\n` +
      `        var dir = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "${asm}");\n` +
      `        Directory.CreateDirectory(dir);\n` +
      `        _statePath = Path.Combine(dir, "state.json");\n` +
      `        _state = LoadState();\n` +
      `        _state.LaunchCount++;\n` +
      `        SaveState();\n` +
      `        statusLabel.Text = $"Launches: {_state.LaunchCount}";\n` +
      `        messageBox.Text = _state.LastMessage;\n` +
      `    }\n\n` +
      `    private AppState LoadState()\n` +
      `    {\n` +
      `        try\n` +
      `        {\n` +
      `            if (File.Exists(_statePath))\n` +
      `                return JsonSerializer.Deserialize<AppState>(File.ReadAllText(_statePath)) ?? new AppState();\n` +
      `        }\n` +
      `        catch { /* corrupted state falls back to defaults */ }\n` +
      `        return new AppState();\n` +
      `    }\n\n` +
      `    private void SaveState() =>\n` +
      `        File.WriteAllText(_statePath, JsonSerializer.Serialize(_state));\n\n` +
      `    private void OnSaveClicked(object? sender, EventArgs e)\n` +
      `    {\n` +
      `        _state.LastMessage = messageBox.Text;\n` +
      `        SaveState();\n` +
      `        statusLabel.Text = $"Saved at {DateTime.Now:T} — launches: {_state.LaunchCount}";\n` +
      `    }\n` +
      `}\n\n` +
      `public sealed class AppState\n` +
      `{\n` +
      `    public int LaunchCount { get; set; }\n` +
      `    public string LastMessage { get; set; } = string.Empty;\n` +
      `}\n`;

    files[`${root}/MainForm.Designer.cs`] =
      `namespace ${asm};\n\n` +
      `partial class MainForm\n` +
      `{\n` +
      `    private System.ComponentModel.IContainer components = null;\n` +
      `    private TextBox messageBox = null!;\n` +
      `    private Button saveButton = null!;\n` +
      `    private Label statusLabel = null!;\n\n` +
      `    protected override void Dispose(bool disposing)\n` +
      `    {\n` +
      `        if (disposing && (components != null)) components.Dispose();\n` +
      `        base.Dispose(disposing);\n` +
      `    }\n\n` +
      `    private void InitializeComponent()\n` +
      `    {\n` +
      `        messageBox = new TextBox();\n` +
      `        saveButton = new Button();\n` +
      `        statusLabel = new Label();\n` +
      `        SuspendLayout();\n` +
      `        // messageBox\n` +
      `        messageBox.Location = new Point(24, 24);\n` +
      `        messageBox.Multiline = true;\n` +
      `        messageBox.Name = "messageBox";\n` +
      `        messageBox.Size = new Size(440, 160);\n` +
      `        // saveButton\n` +
      `        saveButton.Location = new Point(24, 200);\n` +
      `        saveButton.Name = "saveButton";\n` +
      `        saveButton.Size = new Size(120, 32);\n` +
      `        saveButton.Text = "Save";\n` +
      `        saveButton.UseVisualStyleBackColor = true;\n` +
      `        saveButton.Click += OnSaveClicked;\n` +
      `        // statusLabel\n` +
      `        statusLabel.AutoSize = true;\n` +
      `        statusLabel.Location = new Point(160, 208);\n` +
      `        statusLabel.Name = "statusLabel";\n` +
      `        statusLabel.Text = "Ready";\n` +
      `        // MainForm\n` +
      `        AutoScaleDimensions = new SizeF(8F, 20F);\n` +
      `        AutoScaleMode = AutoScaleMode.Font;\n` +
      `        ClientSize = new Size(488, 264);\n` +
      `        Controls.Add(statusLabel);\n` +
      `        Controls.Add(saveButton);\n` +
      `        Controls.Add(messageBox);\n` +
      `        Name = "MainForm";\n` +
      `        Text = "${config.appName}";\n` +
      `        ResumeLayout(false);\n` +
      `        PerformLayout();\n` +
      `    }\n` +
      `}\n`;

    files['.gitignore'] = `bin/\nobj/\n.vs/\n*.user\n`;
    files['Directory.Build.props'] =
      `<Project>\n  <PropertyGroup>\n    <LangVersion>12.0</LangVersion>\n    <Deterministic>true</Deterministic>\n  </PropertyGroup>\n</Project>\n`;

    files['build.ps1'] =
      `# Build ${config.appName} (Windows, PowerShell)\n` +
      `dotnet restore\nif ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }\n` +
      `dotnet build -c Release\n`;
    files['build.sh'] =
      `#!/bin/sh\n# Build ${config.appName} from any host with the .NET 8 SDK\n` +
      `# (EnableWindowsTargeting is set, so Linux/macOS CI can compile the Windows target).\n` +
      `set -e\ndotnet restore\ndotnet build -c Release\n`;

    files['README.md'] =
      `# ${config.appName}\n\n${config.description}\n\n` +
      `Generated by SquadForge (Phase 18 Desktop Development Engine).\n\n` +
      `## Stack\n- C# 12 / .NET 8 (\`${config.targetFramework}\`)\n- Windows Forms (native Windows UI)\n\n` +
      `## Develop\n- Open \`${asm}.sln\` in Visual Studio 2022, or\n- \`dotnet restore\` then \`dotnet build\` (or run build.ps1 / build.sh)\n- Debug in VS Code / Visual Studio with F5; the app entry point is \`src/${asm}/Program.cs\`.\n\n` +
      `## Run\nRun the built executable from \`src/${asm}/bin/Debug/${config.targetFramework}/\` on Windows.\n`;

    return files;
  }
}
