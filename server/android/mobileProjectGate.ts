export interface KotlinToolchain {
  javaBin: string;
  gradleLibDir: string;
  kotlinCompilerJar: string;
  kotlinStdlibJar: string;
  troveJar?: string;
  jetbrainsAnnotationsJar?: string;
  junitJar: string;
  hamcrestJar: string;
  androidJar: string;
  androidPlatform: string;
  /** Real org.json artifact, when one exists on this host (Gradle caches). */
  orgJsonJar?: string;
  /** Pieces that could not be located; empty when the toolchain is complete. */
  missing: string[];
}

function firstExisting(paths: string[]): string | undefined {
  for (const p of paths) {
    try {
      if (p && fs.existsSync(p)) return p;
    } catch { /* keep looking */ }
  }
  return undefined;
}

/** Highest-versioned jar in a directory whose name matches a pattern. */
function findJar(dir: string, pattern: RegExp): string | undefined {
  try {
    const matches = fs.readdirSync(dir).filter(n => pattern.test(n)).sort();
    return matches.length ? path.join(dir, matches[matches.length - 1]) : undefined;
  } catch {
    return undefined;
  }
}

function gradleLibRoots(): string[] {
  const roots: string[] = [];
  if (process.env.F10_GRADLE_LIB_DIR) roots.push(process.env.F10_GRADLE_LIB_DIR);
  if (process.env.GRADLE_HOME) roots.push(path.join(process.env.GRADLE_HOME, 'lib'));
  roots.push(path.join(os.homedir(), '.sdkman', 'candidates', 'gradle', 'current', 'lib'));
  for (const distsRoot of [
    path.join(os.homedir(), 'tools', 'gradle-home', 'wrapper', 'dists'),
    path.join(os.homedir(), '.gradle', 'wrapper', 'dists')
  ]) {
    try {
      for (const dist of fs.readdirSync(distsRoot)) {
        const distDir = path.join(distsRoot, dist);
        for (const hash of fs.readdirSync(distDir)) {
          for (const inner of fs.readdirSync(path.join(distDir, hash))) {
            roots.push(path.join(distDir, hash, inner, 'lib'));
          }
        }
      }
    } catch { /* root absent on this host */ }
  }
  return roots;
}

function androidSdkRoots(): string[] {
  return [
    process.env.ANDROID_HOME,
    process.env.ANDROID_SDK_ROOT,
    path.join(os.homedir(), 'Android', 'Sdk'),
    path.join(os.homedir(), 'Library', 'Android', 'sdk')
  ].filter(Boolean) as string[];
}

function findOrgJsonJar(): string | undefined {
  for (const cacheRoot of [
    path.join(os.homedir(), '.gradle', 'caches', 'modules-2', 'files-2.1', 'org.json'),
    path.join(os.homedir(), 'tools', 'gradle-home', 'caches', 'modules-2', 'files-2.1', 'org.json')
  ]) {
    try {
      const stack = [cacheRoot];
      while (stack.length) {
        const dir = stack.pop()!;
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
          const full = path.join(dir, entry.name);
          if (entry.isDirectory()) stack.push(full);
          else if (/^json-\d+\.jar$/.test(entry.name)) return full;
        }
      }
    } catch { /* cache absent */ }
  }
  return undefined;
}

/**
 * Locates the Kotlin/JVM toolchain from the installations this host
 * (and a standard CI runner) actually has: a JDK, the Gradle
 * distribution's lib directory (embeddable Kotlin compiler, stdlib,
 * JUnit, hamcrest), and the Android SDK platform jar. Nothing is
 * downloaded and nothing is assumed: every piece is reported, and
 * the pieces that are missing are named in `missing`.
 */
export function discoverKotlinToolchain(): KotlinToolchain {
  const missing: string[] = [];

  const javaBin = firstExisting([
    process.env.JAVA_HOME ? path.join(process.env.JAVA_HOME, 'bin', 'java') : '',
    path.join(os.homedir(), 'tools', 'jdk-17', 'bin', 'java')
  ]) || 'java';

  let gradleLibDir = '';
  let kotlinCompilerJar: string | undefined;
  let kotlinStdlibJar: string | undefined;
  let troveJar: string | undefined;
  let jetbrainsAnnotationsJar: string | undefined;
  let junitJar: string | undefined;
  let hamcrestJar: string | undefined;
  for (const root of gradleLibRoots()) {
    const compiler = findJar(root, /^kotlin-compiler-embeddable-.*\.jar$/);
    const stdlib = findJar(root, /^kotlin-stdlib-\d.*\.jar$/);
    const junit = findJar(root, /^junit-4.*\.jar$/) || findJar(root, /^junit-\d.*\.jar$/);
    const hamcrest = findJar(root, /^hamcrest-core-.*\.jar$/);
    if (compiler && stdlib && junit && hamcrest) {
      gradleLibDir = root;
      kotlinCompilerJar = compiler;
      kotlinStdlibJar = stdlib;
      troveJar = findJar(root, /^trove4j-.*\.jar$/);
      jetbrainsAnnotationsJar = findJar(root, /^annotations-\d.*\.jar$/);
      junitJar = junit;
      hamcrestJar = hamcrest;
      break;
    }
    // Remember the best partial root for diagnostics.
    if (!gradleLibDir && (compiler || stdlib)) gradleLibDir = root;
  }
  if (!kotlinCompilerJar) missing.push('kotlin-compiler-embeddable jar (Gradle distribution lib)');
  if (!kotlinStdlibJar) missing.push('kotlin-stdlib jar (Gradle distribution lib)');
  if (!junitJar) missing.push('junit jar (Gradle distribution lib)');
  if (!hamcrestJar) missing.push('hamcrest-core jar (Gradle distribution lib)');

  let androidJar: string | undefined;
  let androidPlatform = '';
  for (const sdk of androidSdkRoots()) {
    const platformsDir = path.join(sdk, 'platforms');
    try {
      const platforms = fs.readdirSync(platformsDir)
        .filter(n => /^android-\d+$/.test(n))
        .sort((a, b) => Number(b.split('-')[1]) - Number(a.split('-')[1]));
      for (const platform of platforms) {
        const jar = path.join(platformsDir, platform, 'android.jar');
        if (fs.existsSync(jar)) {
          androidJar = jar;
          androidPlatform = platform;
          break;
        }
      }
    } catch { /* SDK root absent */ }
    if (androidJar) break;
  }
  if (!androidJar) missing.push('android.jar (Android SDK platform)');

  return {
    javaBin,
    gradleLibDir,
    kotlinCompilerJar: kotlinCompilerJar || '',
    kotlinStdlibJar: kotlinStdlibJar || '',
    troveJar,
    jetbrainsAnnotationsJar,
    junitJar: junitJar || '',
    hamcrestJar: hamcrestJar || '',
    androidJar: androidJar || '',
    androidPlatform,
    orgJsonJar: findOrgJsonJar(),
    missing
  };
}

