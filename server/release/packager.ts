import * as crypto from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import JSZip from 'jszip';
import { TerminalService } from '../ide/terminalService.js';
import { PeInspector } from '../desktop/peInspector.js';
import type { PeInspectionReport } from '../desktop/types.js';
import { generateIconIco, validateIco } from './iconFactory.js';
import { signPeFile, type SigningOutcome } from './signing.js';
import { parseSemVer } from './versioning.js';

/**
 * Phase 23: release packaging. Publishes a desktop project with the
 * real .NET toolchain (`dotnet publish`), stamps metadata + icon,
 * optionally signs (only with a real signer + certificate), and
 * produces a versioned ZIP package with installer scripts and a
 * hash manifest. Build logs are preserved in the package and in the
 * release store.
 */

export interface ReleaseMetadata {
  appName: string;
  version: string;
  publisher: string;
  description: string;
  channel: string;
  selfContained: boolean;
  releaseNotes: string;
  signingCertPath?: string;
  signingCertPassword?: string;
}

export interface ManifestFile {
  path: string;
  sizeBytes: number;
  sha256: string;
}

export interface ReleaseManifest {
  format: 'squadforge-release';
  version: 1;
  appName: string;
  releaseVersion: string;
  publisher: string;
  description: string;
  channel: string;
  createdAt: string;
  runtime: { rid: string; selfContained: boolean };
  exe: ManifestFile & { pe: PeInspectionReport };
  files: ManifestFile[];
  icon: ManifestFile | null;
  signing: SigningOutcome;
  releaseNotes: string;
}

export interface PackageResult {
  manifest: ReleaseManifest;
  packagePath: string;
  packageSizeBytes: number;
  packageSha256: string;
  publishDir: string;
  buildLog: string;
}

const sha256 = (data: Buffer): string => crypto.createHash('sha256').update(data).digest('hex');

export function findCsproj(workspaceRoot: string): string {
  const candidates: string[] = [];
  const walk = (dir: string, depth: number): void => {
    if (depth > 2) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (!['bin', 'obj', 'node_modules', '.git'].includes(entry.name)) walk(path.join(dir, entry.name), depth + 1);
      } else if (entry.name.endsWith('.csproj')) {
        candidates.push(path.relative(workspaceRoot, path.join(dir, entry.name)).split(path.sep).join('/'));
      }
    }
  };
  walk(workspaceRoot, 0);
  if (candidates.length === 0) throw new Error('No .csproj found in the project workspace');
  return candidates.sort()[0];
}

export function installerScripts(metadata: ReleaseMetadata): Record<string, string> {
  const installPs1 = `# ${metadata.appName} ${metadata.version} installer (generated by SquadForge Phase 23)
# Installs per-user to %LOCALAPPDATA%\\Programs\\${metadata.appName} and registers an uninstaller.
$ErrorActionPreference = 'Stop'
$source = Split-Path -Parent $MyInvocation.MyCommand.Path
$dest = Join-Path $env:LOCALAPPDATA 'Programs\\${metadata.appName}'
New-Item -ItemType Directory -Force -Path $dest | Out-Null
Copy-Item -Path (Join-Path $source 'app\\*') -Destination $dest -Recurse -Force
$exe = Join-Path $dest '${metadata.appName}.exe'
$shell = New-Object -ComObject WScript.Shell
$shortcut = $shell.CreateShortcut((Join-Path ([Environment]::GetFolderPath('Programs')) '${metadata.appName}.lnk'))
$shortcut.TargetPath = $exe
$shortcut.Save()
$reg = 'HKCU:\\Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\${metadata.appName}'
New-Item -Path $reg -Force | Out-Null
Set-ItemProperty -Path $reg -Name 'DisplayName' -Value '${metadata.appName}'
Set-ItemProperty -Path $reg -Name 'DisplayVersion' -Value '${metadata.version}'
Set-ItemProperty -Path $reg -Name 'Publisher' -Value '${metadata.publisher}'
Set-ItemProperty -Path $reg -Name 'InstallLocation' -Value $dest
Set-ItemProperty -Path $reg -Name 'UninstallString' -Value "powershell -ExecutionPolicy Bypass -File \`"$dest\\uninstall.ps1\`""
Copy-Item -Path (Join-Path $source 'uninstall.ps1') -Destination (Join-Path $dest 'uninstall.ps1') -Force
Write-Host '${metadata.appName} ${metadata.version} installed to' $dest
`;
  const uninstallPs1 = `# ${metadata.appName} uninstaller
$dest = Join-Path $env:LOCALAPPDATA 'Programs\\${metadata.appName}'
Remove-Item -Path (Join-Path ([Environment]::GetFolderPath('Programs')) '${metadata.appName}.lnk') -Force -ErrorAction SilentlyContinue
Remove-Item -Path 'HKCU:\\Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\${metadata.appName}' -Recurse -Force -ErrorAction SilentlyContinue
Remove-Item -Path $dest -Recurse -Force -ErrorAction SilentlyContinue
Write-Host '${metadata.appName} uninstalled.'
`;
  const inno = `; Inno Setup script for ${metadata.appName} ${metadata.version} (generated by SquadForge Phase 23)
; Compile with Inno Setup 6 (iscc) on Windows to produce a setup .exe.
[Setup]
AppName=${metadata.appName}
AppVersion=${metadata.version}
AppPublisher=${metadata.publisher}
DefaultDirName={autopf}\\${metadata.appName}
OutputBaseFilename=${metadata.appName}-${metadata.version}-setup
Compression=lzma
SolidCompression=yes

[Files]
Source: "app\\*"; DestDir: "{app}"; Flags: recursesubdirs

[Icons]
Name: "{group}\\${metadata.appName}"; Filename: "{app}\\${metadata.appName}.exe"
`;
  return { 'install.ps1': installPs1, 'uninstall.ps1': uninstallPs1, 'installer.iss': inno };
}

export class ReleasePackager {
  /** Run `dotnet publish` for the project in workspaceRoot into <workspace>/.release_out/<version>. */
  public async publishProject(workspaceRoot: string, metadata: ReleaseMetadata): Promise<{ publishDir: string; buildLog: string }> {
    parseSemVer(metadata.version);
    const terminal = new TerminalService(workspaceRoot);
    const csproj = findCsproj(workspaceRoot);
    const outRel = `.release_out/${metadata.version}`;
    const result = await terminal.run(
      'dotnet',
      ['publish', csproj, '-c', 'Release', '-r', 'win-x64', '--self-contained', metadata.selfContained ? 'true' : 'false', '-o', outRel],
      { timeoutMs: 600_000 }
    );
    const buildLog = `$ dotnet publish ${csproj} -c Release -r win-x64 --self-contained ${metadata.selfContained}\n${result.stdout}\n${result.stderr}`;
    if (result.exitCode !== 0) {
      throw new Error(`dotnet publish failed (exit ${result.exitCode}): ${(result.stderr || result.stdout).trim().split('\n').slice(-3).join(' ')}`);
    }
    return { publishDir: path.join(workspaceRoot, outRel), buildLog };
  }

  /** Package a publish directory into the versioned release ZIP + manifest. */
  public async packageRelease(publishDir: string, metadata: ReleaseMetadata, buildLog: string, outPackagePath: string): Promise<PackageResult> {
    const exeName = `${metadata.appName}.exe`;
    const exePath = path.join(publishDir, exeName);
    if (!fs.existsSync(exePath)) {
      throw new Error(`Published executable not found: ${exeName} in ${publishDir}`);
    }

    // Signing (real signer + cert only; otherwise honestly recorded)
    const signing = await signPeFile(exePath, metadata.signingCertPath, metadata.signingCertPassword);

    // Icon: generated genuine ICO, validated before packaging
    const iconBuffer = generateIconIco(metadata.appName);
    const iconCheck = validateIco(iconBuffer);
    if (!iconCheck.valid) throw new Error(`Generated icon failed validation: ${iconCheck.error}`);

    const files: ManifestFile[] = [];
    const zip = new JSZip();
    const appFolder = zip.folder('app')!;
    const walk = (dir: string): void => {
      for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full);
        else {
          const rel = path.relative(publishDir, full).split(path.sep).join('/');
          const data = fs.readFileSync(full);
          files.push({ path: rel, sizeBytes: data.length, sha256: sha256(data) });
          appFolder.file(rel, data);
        }
      }
    };
    walk(publishDir);
    files.sort((a, b) => a.path.localeCompare(b.path));

    const exeData = fs.readFileSync(exePath);
    const pe = PeInspector.inspect(exeData);
    if (!pe.isPeFile) throw new Error(`${exeName} is not a valid PE file — refusing to package`);

    const scripts = installerScripts(metadata);
    for (const [name, content] of Object.entries(scripts)) zip.file(name, content);
    zip.file('app/app.ico', iconBuffer);
    zip.file('build.log', buildLog);

    const manifest: ReleaseManifest = {
      format: 'squadforge-release',
      version: 1,
      appName: metadata.appName,
      releaseVersion: metadata.version,
      publisher: metadata.publisher,
      description: metadata.description,
      channel: metadata.channel,
      createdAt: new Date().toISOString(),
      runtime: { rid: 'win-x64', selfContained: metadata.selfContained },
      exe: { path: exeName, sizeBytes: exeData.length, sha256: sha256(exeData), pe },
      files,
      icon: { path: 'app/app.ico', sizeBytes: iconBuffer.length, sha256: sha256(iconBuffer) },
      signing,
      releaseNotes: metadata.releaseNotes
    };
    zip.file('manifest.json', JSON.stringify(manifest, null, 2));
    zip.file('RELEASE_NOTES.md', `# ${metadata.appName} ${metadata.version}\n\n${metadata.releaseNotes}\n`);

    const packageBuffer = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
    fs.mkdirSync(path.dirname(outPackagePath), { recursive: true });
    fs.writeFileSync(outPackagePath, packageBuffer);
    return {
      manifest,
      packagePath: outPackagePath,
      packageSizeBytes: packageBuffer.length,
      packageSha256: sha256(packageBuffer),
      publishDir,
      buildLog
    };
  }
}
