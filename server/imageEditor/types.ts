export const IMAGE_TOOLS: readonly ImageTool[] = ['brush', 'eraser', 'rectangle', 'ellipse', 'line', 'text', 'fill'];

export interface Viewport {
  /** Pixels of screen per image pixel. */
  zoom: number;
  /** Screen-space offset of the image origin. */
  panX: number;
  panY: number;
}

export interface SerializedLayer {
  id: string;
  name: string;
  visible: boolean;
  opacity: number;
  /** base64 of the raw RGBA bytes */
  pixelsBase64: string;
  /** Phase 44 fields; absent in version-1 files, where defaults apply. */
  blendMode?: BlendMode;
  alphaLock?: boolean;
  clipped?: boolean;
  groupId?: string | null;
  /** base64 of the mask's grayscale bytes, or null/absent when no mask */
  maskBase64?: string | null;
  /**
   * Phase 48 fields; absent in files written before Phase 48, where
   * every layer loads as a raster layer from its pixels. The text /
   * shape payloads are plain JSON data (colors and points are plain
   * objects), stored field-for-field.
   */
  kind?: LayerKind;
  text?: TextLayerData | null;
  shape?: VectorShapeData | null;
  contentTransform?: number[] | null;
  /**
   * Phase 52 fields; absent in files written before Phase 52, where
   * every layer loads with an empty effect stack and no placement.
   * `effects` entries are validated against the Phase 47 registry on
   * load (unknown ids / bad params are rejected, never stored);
   * `placement` is a 9-number matrix like `contentTransform`.
   */
  effects?: LayerEffect[];
  placement?: number[] | null;
}

export interface SerializedGroup {
  id: string;
  name: string;
  parentId: string | null;
  visible: boolean;
  opacity: number;
  blendMode: BlendMode;
}

export interface SerializedProject {
  format: 'squadforge-image-project';
  /** 1 = Phase 19 format (no groups/masks/blend modes); 2 = Phase 44 format (Phase 48 adds optional per-layer content fields). Both load. */
  version: 1 | 2;
  width: number;
  height: number;
  activeLayerId: string | null;
  layers: SerializedLayer[];
  /** Phase 44; absent in version-1 files. */
  groups?: SerializedGroup[];
  /**
   * Phase 54 fields; absent in files written before Phase 54, where a
   * project loads with no guides and the default grid. Present values
   * are validated on load (bad orientation / non-finite position /
   * non-positive grid spacing are rejected, never silently loaded).
   */
  guides?: GuideLine[];
  grid?: GridSettings;
}

/**
 * Phase 47: one numeric parameter of a filter, as described to a UI:
 * the parameter's name, its accepted range and the default used when
 * the caller omits it. Applying a filter validates every supplied
 * parameter against this schema — unknown names and out-of-range
 * values are rejected, never silently clamped.
 */
export interface FilterParamSpec {
  name: string;
  min: number;
  max: number;
  defaultValue: number;
}

/**
 * Phase 47: a filter in the registry. The descriptor is pure data (a
 * UI can render controls from it); the implementation lives in
 * imageCore.ts beside it and is only reachable through the validated
 * apply/preview functions.
 */
export interface FilterDescriptor {
  id: string;
  name: string;
  params: FilterParamSpec[];
}

/**
 * Phase 47: scoping for a filter application — the same two scoping
 * forms the painting tools accept. `selection` is the Phase 19 rect
 * (hard in/out); `selectionMask` is the Phase 45 raster selection and
 * weights the filter per pixel by value/255, so feathered selection
 * edges blend the filtered and original pixels smoothly.
 */
export interface FilterOptions {
  selection?: Rect | null;
  selectionMask?: SelectionMask | null;
}

/**
 * Phase 48: layer content kinds. 'raster' is the Phase 19 pixel layer;
 * 'text' and 'shape' are content layers whose pixels are rendered from
 * editable data (see Layer). Phase 52 adds 'adjustment': a layer with
 * no pixels of its own whose effect stack filters the backdrop below
 * it at composite time.
 */
export type LayerKind = 'raster' | 'text' | 'shape' | 'adjustment';

export const LAYER_KINDS: readonly LayerKind[] = ['raster', 'text', 'shape', 'adjustment'];

/**
 * Phase 48: the built-in typefaces a text layer can name. These are
 * the only fonts that exist in this engine — both are drawn from the
 * glyph tables in bitmapFont.ts (there is no system-font access):
 * 'pixel' is the Phase 19 5x7 set; 'pixel-bold' is its bold companion
 * set, materialized from the regular set by a 1px horizontal dilation.
 */
export type BuiltInFontId = 'pixel' | 'pixel-bold';

export const BUILT_IN_FONT_IDS: readonly BuiltInFontId[] = ['pixel', 'pixel-bold'];

export type TextAlign = 'left' | 'center' | 'right';

export const TEXT_ALIGNS: readonly TextAlign[] = ['left', 'center', 'right'];

/** Phase 48: a text outline (stroke) — width in whole pixels, drawn under the fill. */
export interface TextOutline {
  /** Whole pixels, 0..64. 0 (or a null outline) draws no outline. */
  width: number;
  color: RgbaColor;
}

/** Phase 48: a text drop shadow, drawn under the outline and fill. */
export interface TextShadow {
  offsetX: number;
  offsetY: number;
  /** Box-blur radius applied to the shadow's coverage, in pixels (>= 0). */
  blur: number;
  color: RgbaColor;
}

/**
 * Phase 48: the editable data of a text layer. Rendering is
 * deterministic: the text is set in the named built-in bitmap font at
 * an integer scale derived from `fontSize` (the glyph grid is 5x7, so
 * the effective glyph height is 7 * round(fontSize / 7), at least 7),
 * laid out line by line (split on '\n') from `origin`, each line
 * aligned within the block width. `blockWidth` 0 means "as wide as
 * the widest line", so alignment is then relative to the content.
 * `letterSpacing` is extra pixels between glyphs, `lineSpacing`
 * extra pixels between lines; both are >= 0.
 */
export interface TextLayerData {
  text: string;
  font: BuiltInFontId;
  /** Nominal glyph height in pixels; snaps to the bitmap grid (see above). */
  fontSize: number;
  align: TextAlign;
  letterSpacing: number;
  lineSpacing: number;
  color: RgbaColor;
  outline: TextOutline | null;
  shadow: TextShadow | null;
  /** Top-left of the text block, in canvas coordinates. */
  origin: Point;
  /** Block width used for alignment; 0 = widest line. */
  blockWidth: number;
}

/**
 * Phase 48: one cubic Bézier segment. The curve runs from `p0` to
 * `p1`; `c1` and `c2` are the control points of the standard cubic
 * formula B(t) = (1-t)^3 p0 + 3(1-t)^2 t c1 + 3(1-t) t^2 c2 + t^3 p1.
 */
export interface BezierSegment {
  p0: Point;
  c1: Point;
  c2: Point;
  p1: Point;
}

export type VectorShapeKind = 'rectangle' | 'ellipse' | 'line' | 'polygon' | 'path';

export const VECTOR_SHAPE_KINDS: readonly VectorShapeKind[] = ['rectangle', 'ellipse', 'line', 'polygon', 'path'];

/**
 * Phase 48: the editable data of a vector shape layer. Geometry is
 * stored per kind (only the fields for `kind` are non-null):
 * `rect` bounds a rectangle or an ellipse, `from`/`to` are a line's
 * endpoints, `points` are a polygon's vertices, `segments` are a
 * path's cubic Bézier segments (expected to be continuous: each
 * segment's p0 is the previous segment's p1). Fill applies to closed
 * shapes (rectangle, ellipse, polygon, and paths with `closed`);
 * stroke is drawn along the shape's outline with `strokeWidth`.
 * A null fill/stroke (or a strokeWidth of 0) omits that paint.
 */
export interface VectorShapeData {
  kind: VectorShapeKind;
  rect: Rect | null;
  from: Point | null;
  to: Point | null;
  points: Point[] | null;
  segments: BezierSegment[] | null;
  closed: boolean;
  fill: RgbaColor | null;
  stroke: RgbaColor | null;
  strokeWidth: number;
}

