/**
 * Phase 19: Image Editing Engine — shared types.
 *
 * The engine works on real RGBA pixel buffers. A project is a stack of
 * layers (index 0 = bottom). All operations mutate or produce genuine
 * pixel data — there is no simulated rendering anywhere in this module.
 */

export interface PixelImage {
  width: number;
  height: number;
  /** RGBA, row-major, length = width * height * 4 */
  data: Uint8ClampedArray;
}

/**
 * Phase 50: a first-class grayscale working image — one channel per
 * pixel, the same single-channel representation the engine already
 * uses for masks, selections and brush tips. There is deliberately
 * no alpha channel: converting RGBA to grayscale discards alpha
 * (documented at `rgbaToGrayscale`), it is never silently kept.
 */
export interface GrayImage {
  width: number;
  height: number;
  /** Grayscale, row-major, length = width * height */
  data: Uint8ClampedArray;
}

/**
 * Phase 50: a 16-bit-per-channel RGBA working image. Values are
 * 0..65535 per channel in a Uint16Array, so operations performed on
 * this representation genuinely carry more precision than the 8-bit
 * PixelImage — see `colorManagement.ts` for the conversion rules and
 * the operations that run natively in 16-bit.
 */
export interface PixelImage16 {
  width: number;
  height: number;
  /** RGBA 16-bit, row-major, length = width * height * 4 */
  data: Uint16Array;
}

/**
 * Blend modes for compositing a layer (or a flattened group) over the
 * backdrop below it. 'normal' is classic source-over; the rest apply the
 * W3C blend functions per channel before alpha compositing. Phase 44
 * added multiply/screen/overlay/darken/lighten.
 */
export type BlendMode = 'normal' | 'multiply' | 'screen' | 'overlay' | 'darken' | 'lighten';

export const BLEND_MODES: readonly BlendMode[] = ['normal', 'multiply', 'screen', 'overlay', 'darken', 'lighten'];

/**
 * Phase 44: an editable grayscale layer mask. Single channel, same
 * dimensions as the owning layer's image: 255 reveals the layer pixel,
 * 0 hides it, values between scale its effective alpha when compositing.
 */
export interface LayerMask {
  width: number;
  height: number;
  /** Grayscale, row-major, length = width * height */
  data: Uint8ClampedArray;
}

export interface Layer {
  id: string;
  name: string;
  visible: boolean;
  /** 0..1 */
  opacity: number;
  image: PixelImage;
  /**
   * Phase 48: what this layer's pixels mean. 'raster' layers are plain
   * pixel buffers (the Phase 19 model). 'text' and 'shape' layers are
   * content layers: `image` is a deterministic render cache of the
   * editable data in `text` / `shape` (placed by `contentTransform`),
   * regenerated by every content mutator — the data, not the cache,
   * is the source of truth.
   *
   * Phase 52: 'adjustment' layers carry no pixels of their own (their
   * `image` is an empty canvas-sized buffer kept only for the engine's
   * canvas-size invariant). At composite time an adjustment layer
   * applies its `effects` stack to the accumulated backdrop of its
   * compositing level below it — see `effects` and Phase 52 notes in
   * imageCore.ts.
   */
  kind: LayerKind;
  /** Phase 48: editable text data when kind === 'text', else null. */
  text: TextLayerData | null;
  /** Phase 48: editable vector shape data when kind === 'shape', else null. */
  shape: VectorShapeData | null;
  /**
   * Phase 48: placement of a content layer's rendering — a row-major
   * 3x3 projective matrix (the Phase 45 Mat3 form) mapping untransformed
   * content coordinates to canvas coordinates, or null for identity.
   * Transforms of content layers compose into this matrix instead of
   * baking into pixels, so the content stays editable afterwards.
   */
  contentTransform: number[] | null;
  /** Phase 44: how this layer blends over the backdrop. Default 'normal'. */
  blendMode: BlendMode;
  /** Phase 44: grayscale mask modulating this layer's alpha, or null. */
  mask: LayerMask | null;
  /** Phase 44: when true, paint operations may not change this layer's alpha. */
  alphaLock: boolean;
  /** Phase 44: when true, this layer is clipped to the alpha footprint of the nearest non-clipped node below it in the same group level. */
  clipped: boolean;
  /** Phase 44: id of the LayerGroup this layer belongs to, or null for the root level. */
  groupId: string | null;
  /**
   * Phase 52: the layer's non-destructive effect stack — an ordered
   * list of Phase 47 registry filters applied at render time to the
   * layer's pristine pixels (for content layers: to the render cache;
   * for adjustment layers: to the backdrop below). The stored pixels
   * are never modified by the stack; only `bakeLayerEffects` writes
   * the stacked result into a raster layer's pixels, and it clears
   * the stack when it does. Empty for most layers.
   */
  effects: LayerEffect[];
  /**
   * Phase 52: a raster layer's non-destructive placement — a row-major
   * 3x3 projective matrix (the Phase 45 Mat3 form, the same storage
   * form as `contentTransform`) mapping the layer's pristine pixels
   * into canvas coordinates, or null for identity. Set from a Phase 45
   * Transform2D via `setLayerPlacement`; while a placement is set, the
   * Phase 45 transform family composes into it instead of baking
   * pixels, and clearing it restores the byte-exact original render.
   * Raster layers only: content layers place via `contentTransform`,
   * adjustment layers have no pixels to place.
   */
  placement: number[] | null;
}

/**
 * Phase 44: a layer group. Groups nest via parentId (null = root level).
 * A group composites its children into an isolated buffer, which is then
 * blended over the backdrop with the group's own opacity and blend mode;
 * an invisible group hides its whole subtree.
 */
export interface LayerGroup {
  id: string;
  name: string;
  parentId: string | null;
  visible: boolean;
  /** 0..1 */
  opacity: number;
  blendMode: BlendMode;
}

export interface ImageProject {
  width: number;
  height: number;
  layers: Layer[];
  /** Phase 44: layer groups (possibly empty). Layers reference them via groupId. */
  groups: LayerGroup[];
  activeLayerId: string | null;
  /** Phase 54: ruler guide lines placed on the canvas (see workspace.ts). */
  guides: GuideLine[];
  /** Phase 54: the document grid that snapping can target (see workspace.ts). */
  grid: GridSettings;
}

/** Phase 54: a ruler guide line. 'horizontal' guides run across the canvas at y = position; 'vertical' guides run down it at x = position. */
export type GuideOrientation = 'horizontal' | 'vertical';

export const GUIDE_ORIENTATIONS: readonly GuideOrientation[] = ['horizontal', 'vertical'];

export interface GuideLine {
  orientation: GuideOrientation;
  /** Canvas coordinate along the guide's axis, in image pixels. Any finite value is storable; guides outside the canvas simply never snap visibly. */
  position: number;
}

/**
 * Phase 54: the document grid. Grid lines along an axis sit at
 * offset + k * spacing for every integer k. Spacings must be > 0.
 */
export interface GridSettings {
  spacingX: number;
  spacingY: number;
  offsetX: number;
  offsetY: number;
}

export const DEFAULT_GRID_SETTINGS: GridSettings = { spacingX: 16, spacingY: 16, offsetX: 0, offsetY: 0 };

/**
 * Phase 52: one entry of a layer's non-destructive effect stack.
 * `filterId` names a Phase 47 registry filter; `params` are the
 * filter's parameters as resolved by `resolveFilterParams` at the
 * time the effect was added or last edited (defaults filled in, so
 * the stored form is complete and stable across serialization).
 * Disabled effects stay in the stack but are skipped at render time.
 */
export interface LayerEffect {
  filterId: string;
  params: Record<string, number>;
  enabled: boolean;
}

/**
 * Phase 45: a professional selection, stored the same way as a layer
 * mask — a single-channel grayscale raster the size of the canvas.
 * 255 = fully selected, 0 = not selected, values between are partial
 * (feathered) selection. Selections are session-level values passed to
 * the selection/transform functions; they bridge into the persisted
 * model by becoming a layer mask (`applySelectionAsMask`).
 */
export interface SelectionMask {
  width: number;
  height: number;
  /** Grayscale, row-major, length = width * height */
  data: Uint8ClampedArray;
}

/**
 * Phase 45: the transform model behind the transform handles. A layer,
 * group or selection is scaled, then rotated, about (`centerX`,
 * `centerY`) — the handle the user drags the rotation around — then
 * translated by (`translateX`, `translateY`). Angles are degrees;
 * positive rotation follows the engine's existing `rotateImage`
 * convention (the +90° step rotation). Resampling is bilinear.
 */
export interface Transform2D {
  translateX: number;
  translateY: number;
  scaleX: number;
  scaleY: number;
  /** Degrees, about (centerX, centerY). */
  rotationDeg: number;
  centerX: number;
  centerY: number;
}

/**
 * Phase 46: a custom brush tip — a grayscale raster used as the stamp
 * shape. 255 = full paint at that texel, 0 = no paint. The same
 * single-channel representation as a layer mask or a selection.
 */
export interface BrushTip {
  width: number;
  height: number;
  /** Grayscale, row-major, length = width * height */
  data: Uint8ClampedArray;
}

/**
 * Phase 46: the advanced brush model. Painting accumulates a coverage
 * map over the stroke: each stamp deposits `shape × flow` coverage
 * (build-up rule cov += deposit × (1 − cov), so repeated stamps
 * approach full coverage at a rate set by flow), and the finished
 * stroke is applied once at `opacity` — opacity is the stroke-level
 * cap, flow the per-stamp rate, exactly the distinction painting
 * applications draw. `spacing` is the stamp interval as a fraction of
 * the brush diameter (values above 1 leave gaps). `smoothing` is
 * stroke stabilization strength (0 = raw input path). `tip` is null
 * for the round tip, whose edge profile is set by `hardness`
 * (1 = hard edge, 0 = linear falloff across the whole radius).
 * `pressureSize` / `pressureOpacity` route per-point stroke pressure
 * into stamp diameter / stamp strength.
 */
export interface BrushSettings {
  /** Stamp diameter in pixels (> 0). */
  size: number;
  /** 0..1, round-tip edge profile. Ignored for custom tips. */
  hardness: number;
  /** Stamp interval as a fraction of `size` (>= 0). */
  spacing: number;
  /** 0..1, stroke-level alpha cap. */
  opacity: number;
  /** 0..1, per-stamp build-up rate. */
  flow: number;
  /** 0..1, stroke stabilization strength. */
  smoothing: number;
  /** Custom stamp shape, or null for the round tip. */
  tip: BrushTip | null;
  /** When true, per-point pressure scales the stamp diameter. */
  pressureSize: boolean;
  /** When true, per-point pressure scales the stamp strength. */
  pressureOpacity: boolean;
}

/**
 * Phase 46: one point of an advanced-brush stroke. `pressure` is the
 * input device's reported pressure in 0..1 when the device provides
 * it; it is absent (and treated as a full 1) when it does not — the
 * engine models pressure as input data and never fabricates a
 * hardware reading.
 */
export interface StrokePoint extends Point {
  pressure?: number;
}

/** Phase 46: a named, reusable bundle of brush settings. */
export interface BrushPreset {
  name: string;
  settings: BrushSettings;
}

/** Phase 46: the JSON-safe serialized form of a brush preset (tip bytes as base64). */
export interface SerializedBrushPreset {
  format: 'squadforge-brush-preset';
  version: 1;
  name: string;
  settings: {
    size: number;
    hardness: number;
    spacing: number;
    opacity: number;
    flow: number;
    smoothing: number;
    pressureSize: boolean;
    pressureOpacity: boolean;
    tip: { width: number; height: number; dataBase64: string } | null;
  };
}

export interface Rect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface Point {
  x: number;
  y: number;
}

export interface RgbaColor {
  r: number;
  g: number;
  b: number;
  a: number;
}

