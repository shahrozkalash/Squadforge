function okStubResult(modelId: string, parsedResponse: any, rawText = ''): any {
  return {
    success: true,
    rawText,
    parsedResponse,
    tokensUsed: 10,
    modelId,
    actualModelUsed: modelId,
    providerUsed: 'stub-transport',
    isFallback: false,
    latencyMs: 1
  };
}

/**
 * Install the patch-aware stub transport for one category fixture
 * (the F9 suite's installer, generalized only in that the fixture's
 * planner actions and content function are parameters). The planner
 * call returns the fixture's create_task actions; the verifier call
 * approves; worker calls write the fixture's file contents for the
 * task's declared file paths — patching a file that already exists
 * with different content (the project manager pre-creates README.md
 * during planning, and a create_file for an existing file aborts
 * the batch), creating the rest, and omitting a file that is
 * already exactly as intended.
 */
export function installFactoryStub(
  t: any,
  plannerActions: any[],
  contentFor: (filePath: string) => string
): void {
  assert.ok(
    Array.isArray(plannerActions) && plannerActions.length > 0,
    'the fixture must declare planner actions'
  );
  t.mock.method(smartRouter, 'executeSmartRequest', async (params: any) => {
    const modelId: string = params.requestedModelId || 'unknown';
    const prompt: string = params.prompt || '';

    if (prompt.includes('PROJECT MANAGER & ARCHITECT SPECIFICATION')) {
      return okStubResult(modelId, { thinking: 'plan', actions: plannerActions });
    }
    if (prompt.includes('VERIFY SOFTWARE COMPLETION')) {
      return okStubResult(modelId, null, JSON.stringify({
        approved: true,
        summary: 'All requirements verified against specification',
        missingRequirements: []
      }));
    }

    const task = params.task;
    const actions = (task?.filePaths || [])
      .map((p: string) => {
        const existing = db.getFile(params.buildId, p);
        if (existing && existing.content !== contentFor(p)) {
          return { action: 'patch_file', path: p, edits: [{ find: existing.content, replace: contentFor(p) }], commitMessage: 'Implement ' + task?.title };
        }
        if (existing) return null;
        return { action: 'create_file', path: p, content: contentFor(p), commitMessage: 'Implement ' + task?.title };
      })
      .filter(Boolean);
    return okStubResult(modelId, { thinking: 'work', actions });
  });
}

