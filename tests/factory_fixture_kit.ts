// The F12 stub provider: a loopback OpenAI-compatible endpoint that
// records every request (url, model, auth presence) and answers with
// the platform report shape carrying STUB_ANSWER. This is the Phase
// 33 seam — the delivered app talks to the REAL platform gateway,
// which routes to this endpoint as its upstream.
// ---------------------------------------------------------------------------

export interface AiStubProviderKit {
  provider: AiStubProvider;
  seen: Array<{ url: string; model: string; hasAuth: boolean }>;
  close: () => Promise<void>;
}

export async function createAiStubProvider(): Promise<AiStubProviderKit> {
  const seen: Array<{ url: string; model: string; hasAuth: boolean }> = [];
  const server = http.createServer((req, res) => {
    let raw = '';
    req.on('data', chunk => (raw += chunk));
    req.on('end', () => {
      let model = '';
      try {
        model = JSON.parse(raw || '{}').model ?? '';
      } catch {
        model = '';
      }
      seen.push({ url: req.url ?? '', model, hasAuth: Boolean(req.headers.authorization) });
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(
        JSON.stringify({
          id: 'chatcmpl-f13-stub',
          object: 'chat.completion',
          choices: [
            {
              index: 0,
              message: {
                role: 'assistant',
                content: JSON.stringify({ report: { answer: STUB_ANSWER } })
              },
              finish_reason: 'stop'
            }
          ],
          usage: { prompt_tokens: 12, completion_tokens: 9, total_tokens: 21 }
        })
      );
    });
  });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address();
  if (!address || typeof address === 'string') throw new Error('stub provider failed to bind');
  return {
    provider: { baseUrl: `http://127.0.0.1:${address.port}/v1`, apiKey: 'f13-stub-provider-key' },
    seen,
    close: () =>
      new Promise<void>(resolve => {
        server.closeAllConnections?.();
        server.close(() => resolve());
      })
  };
}

