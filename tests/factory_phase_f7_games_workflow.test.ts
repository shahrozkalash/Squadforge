test('F7 workflow: a game with an injected runtime error is not delivered as playable', { timeout: 60_000 }, async () => {
  const clean = GameWorkflow.assessPlayability({ ...GAME_FILES });
  assert.equal(clean.playable, true, `control: the genuine game must be playable (${clean.runtimeErrors.join('; ')})`);

  const needle = 'world.time += dt;';
  assert.ok(GAME_FILES['game.js'].includes(needle), 'the injection needle must exist in the shipped core');
  const brokenJs = GAME_FILES['game.js'].replace(
    needle,
    `${needle} throw new Error('Injected runtime fault (F7)');`
  );
  assert.notEqual(brokenJs, GAME_FILES['game.js']);

  const broken = GameWorkflow.assessPlayability({ ...GAME_FILES, 'game.js': brokenJs });
  assert.equal(broken.playable, false, 'a game whose step function throws must not be playable');
  assert.ok(
    broken.runtimeErrors.some(e => e.includes('Injected runtime fault (F7)')),
    `the runtime error must be captured and named, got: ${broken.runtimeErrors.join('; ')}`
  );

  // The workflow's delivery verdict refuses it even with green tests
  // and a real artifact — playability is a hard gate, not a label.
  const verdict = GameWorkflow.verifyDelivery({
    tests: { status: 'passed', mode: 'project_tests', total: 2, passed: 2, failed: 0, skipped: 0, detail: 'fixture' },
    artifact: { name: 'game.zip', kind: 'zip', sizeBytes: 4096, sha256: 'a'.repeat(64) },
    playability: broken
  });
  assert.equal(verdict, false, 'a delivery whose game fails playability must not verify');
});

