test('F7 workflow: 3D variant generates the Phase 21-stack game project and exports parseable OBJ/glTF', { timeout: 60_000 }, async () => {
  const files = GameProjectGenerator.generateWinForms3dGame(GameProjectGenerator.getDefaultConfig('CubeQuest'));
  for (const expected of [
    'CubeQuest.sln',
    'src/CubeQuest/CubeQuest.csproj',
    'src/CubeQuest/Program.cs',
    'src/CubeQuest/MainForm.cs',
    'src/CubeQuest/SceneDocument.cs',
    'src/CubeQuest/Viewport3D.cs'
  ]) {
    assert.ok(files[expected], `the 3D game project must contain ${expected}`);
  }
  assert.match(files['src/CubeQuest/MainForm.cs'], /CubeQuest/, 'the generated game must be the CubeQuest collection game');

  // The game's arena as a scene on the Phase 21 engine: ground plane,
  // hero cube (animated), five pickup cubes — the CubeQuest design.
  const scene = createScene('CubeQuest Arena');
  const ground = addNode(scene, 'Ground');
  ground.mesh = createPlaneMesh(20, 20);
  ground.material = defaultMaterial('Ground');
  const hero = addNode(scene, 'Hero');
  hero.mesh = createCubeMesh(1.2);
  hero.material = { ...defaultMaterial('Hero'), color: { r: 0.95, g: 0.6, b: 0.1 } };
  hero.transform.position = vec3(0, 0.6, 0);
  addKeyframe(scene, hero.id, 'position', 0, vec3(0, 0.6, 0));
  addKeyframe(scene, hero.id, 'position', 2, vec3(3, 0.6, 0));
  for (let i = 0; i < 5; i++) {
    const pickup = addNode(scene, `Pickup ${i + 1}`);
    pickup.mesh = createCubeMesh(0.7);
    pickup.material = { ...defaultMaterial('Pickup'), color: { r: 0.3, g: 0.85, b: 0.4 } };
    pickup.transform.position = vec3(-6 + i * 3, 0.35, i % 2 === 0 ? -4 : 4);
  }

  // OBJ: parse the text format back — vertices, faces, indices in range.
  const { obj, mtl } = exportObj(scene);
  const vLines = obj.split('\n').filter(l => l.startsWith('v '));
  const fLines = obj.split('\n').filter(l => l.startsWith('f '));
  assert.ok(vLines.length > 0, 'OBJ export must contain vertices');
  assert.ok(fLines.length > 0, 'OBJ export must contain faces');
  for (const line of fLines) {
    for (const corner of line.slice(2).trim().split(/\s+/)) {
      const vertexIndex = Number(corner.split('/')[0]);
      assert.ok(
        Number.isInteger(vertexIndex) && vertexIndex >= 1 && vertexIndex <= vLines.length,
        `OBJ face index ${vertexIndex} must reference an exported vertex (1..${vLines.length})`
      );
    }
  }
  assert.match(mtl, /newmtl Hero/, 'the MTL must carry the scene materials');

  // glTF: parse the JSON — structure, accessors, and an embedded buffer
  // whose decoded length matches its declared byteLength.
  const gltf: any = exportGltf(scene);
  assert.equal(gltf.asset.version, '2.0');
  assert.ok(Array.isArray(gltf.meshes) && gltf.meshes.length >= 6, `expected ground + hero + 5 pickups as meshes, got ${gltf.meshes?.length}`);
  assert.ok(Array.isArray(gltf.accessors) && gltf.accessors.length > 0, 'glTF must carry accessors');
  const bin = Buffer.from(gltf.buffers[0].uri.split(',')[1], 'base64');
  assert.equal(bin.length, gltf.buffers[0].byteLength, 'the embedded buffer must decode to its declared byteLength');
  for (const view of gltf.bufferViews) {
    assert.ok(view.byteOffset + view.byteLength <= bin.length, 'every bufferView must lie inside the buffer');
  }
  assert.equal(gltf.animations.length, 1, 'the hero keyframes must export as one animation');
});

