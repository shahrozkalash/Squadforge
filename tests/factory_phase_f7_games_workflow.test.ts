function gameContentFor(filePath: string): string {
  if (filePath === 'package.json') return GAME_PACKAGE_JSON;
  if (filePath === 'tsconfig.json') return GAME_TSCONFIG;
  if (filePath === 'tests/game.test.ts') return GAME_TEST_TS;
  const generated = GAME_FILES[filePath];
  if (generated !== undefined) return generated;
  return `// ${filePath}\n`;
}

