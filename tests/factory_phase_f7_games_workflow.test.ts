test('F7 workflow: described 2D game flows team → swarm build → environment cycle → playable delivery', { timeout: 300_000 }, async (t) => {
  // Step 1 — team resolution from F5 data.
  const plan = GameWorkflow.plan(DESCRIPTION);
  assert.equal(plan.category, 'game_application');
  assert.equal(plan.teamName, 'Game Development Team');
  assert.equal(plan.profileId, 'game_creative_application');
  assert.ok(plan.resolvedTeam.members.length >= 5, 'the game team must have members');
  for (const member of plan.resolvedTeam.members) {
    assert.ok(member.modelId, `team member role ${member.role} must resolve to a registered model`);
  }
  assert.equal(plan.resolvedTeam.verifierModelId, 'claude', 'the game team verification chain resolves its verifier through the registry');

  // Step 2 — swarm build through the F4 gates.
  const { buildId, userId } = makeBuild();
  installGameStub(t);
  const stopPump = startApprovalPump(buildId, userId);
  try {
    await SwarmOrchestrator.startSwarm(buildId);
  } finally {
    stopPump();
  }

  const build = db.getBuild(buildId);
  const tasks = db.getTasks(buildId);
  const planned = tasks.filter(task => !task.isFixTask);
  const events = db.getEvents(buildId);

  assert.equal(build?.status, 'completed', `swarm build must complete, got ${build?.status}: ${build?.error || build?.failureReason || ''}`);
  assert.equal(build?.projectType, 'game_application', 'the build must be classified as a game by the platform analyzer');
  assert.ok(events.some(e => e.type === 'verifier_approved'), 'the completion verifier must approve before completion');
  for (const e of events.filter(e => e.type === 'sandbox_check')) {
    assert.match(e.details, /passed cleanly/, 'every sandbox integrity check in the run must pass');
  }
  assert.ok(planned.length >= 4, `expected the planner's game tasks, got ${planned.length}`);
  for (const task of planned) {
    assert.equal(task.status, 'completed', `task "${task.title}" must complete`);
  }

  // The built tree is the genuine game project, byte-identical to the
  // platform generator's output for the game files.
  for (const filePath of ['game.js', 'index.html', 'styles.css', 'package.json', 'tsconfig.json', 'tests/game.test.ts']) {
    assert.ok(db.getFile(buildId, filePath), `the built tree must contain ${filePath}`);
  }
  assert.equal(db.getFile(buildId, 'game.js')!.content, GAME_FILES['game.js'], 'the shipped game.js must be the generator output byte-for-byte');
  assert.equal(db.getFile(buildId, 'index.html')!.content, GAME_FILES['index.html']);

  // Steps 3–4 — environment cycle through the F6 contract + playability.
  const delivery = await GameWorkflow.runEnvironmentCycle({ projectId: buildId, userId, title: DESCRIPTION });

  assert.equal(
    delivery.build.status,
    'skipped',
    `a static HTML5 game has no bundle entry point, so the web build validation must honestly skip, got ${delivery.build.status}: ${delivery.build.detail}`
  );
  assert.equal(delivery.tests.status, 'passed', `the contract test cycle must pass: ${delivery.tests.detail}`);
  assert.equal(delivery.tests.failed, 0);
  assert.ok(delivery.tests.passed >= 2, `the project's own gameplay tests must run and pass, got ${delivery.tests.passed}`);
  assert.ok(typeof delivery.previewMode === 'string' && delivery.previewMode.length > 0, 'a preview must be produced with its mode labelled');

  assert.equal(delivery.artifact.kind, 'zip');
  assert.ok(delivery.artifact.sizeBytes > 0, 'the exported artifact must be non-empty');
  assert.match(delivery.artifact.sha256 || '', /^[0-9a-f]{64}$/, 'the exported artifact must carry a SHA-256');
  assert.ok(delivery.artifact.path && fs.existsSync(delivery.artifact.path), 'the exported artifact must exist on disk');
  const artifactBytes = fs.readFileSync(delivery.artifact.path!);
  assert.equal(
    crypto.createHash('sha256').update(artifactBytes).digest('hex'),
    delivery.artifact.sha256,
    'the artifact hash must match the bytes on disk'
  );
  assert.ok(artifactBytes.length > 0, 'the artifact archive on disk must be non-empty');
  // Note: the contract's artifact.sizeBytes is ProductionBuilder's
  // total — the uncompressed size of the packaged bundle contents —
  // not the ZIP archive length; the hash above is the byte-exact check.

  // Playability: the delivered game actually plays, headlessly.
  assert.equal(delivery.playability.runtimeErrors.length, 0, `no runtime errors: ${delivery.playability.runtimeErrors.join('; ')}`);
  for (const check of delivery.playability.checks) {
    assert.ok(check.passed, `playability check "${check.name}" must pass: ${check.detail}`);
  }
  assert.equal(delivery.playability.playable, true);
  // Step budget: 90 settle + 60 input + two scripted plays (90 settle +
  // ~35–70 walk/jump steps each) — a deterministic total of ~412 steps.
  assert.ok(delivery.playability.stepsSimulated >= 400, `the simulation must run a real number of steps, got ${delivery.playability.stepsSimulated}`);
  assert.ok((delivery.playability.finalState?.coins ?? 0) >= 1, 'scripted play must collect a coin');
  assert.ok((delivery.playability.finalState?.score ?? 0) >= 100, 'scripted play must score');

  assert.equal(delivery.verified, true, 'the delivery must be verified: tests passed + artifact exported + game playable');
});

