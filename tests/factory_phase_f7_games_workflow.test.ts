test('F7 workflow: multiplayer foundation — two clients in sync, cheat attempt rejected', { timeout: 60_000 }, async () => {
  const server = new GameServer();
  const port = await server.start(0);
  const url = `ws://127.0.0.1:${port}`;
  const mkClient = (): { ws: WebSocket; messages: any[] } => {
    const ws = new WebSocket(url);
    const messages: any[] = [];
    ws.addEventListener('message', (event: any) => {
      try { messages.push(JSON.parse(String(event.data))); } catch { /* ignore */ }
    });
    return { ws, messages };
  };
  const waitFor = async (cond: () => boolean, what: string): Promise<void> => {
    const deadline = Date.now() + 10_000;
    while (!cond()) {
      if (Date.now() > deadline) throw new Error(`Timed out waiting for ${what}`);
      await new Promise(r => setTimeout(r, 25));
    }
  };
  const statesOf = (c: { messages: any[] }): any[] => c.messages.filter(m => m.type === 'state');

  try {
    const a = mkClient();
    const b = mkClient();
    await waitFor(() => a.messages.some(m => m.type === 'welcome'), 'welcome A');
    await waitFor(() => b.messages.some(m => m.type === 'welcome'), 'welcome B');
    await waitFor(() => server.stats().clients === 2, 'two clients registered');
    a.ws.send(JSON.stringify({ type: 'join', name: 'F7-A' }));
    b.ws.send(JSON.stringify({ type: 'join', name: 'F7-B' }));
    await waitFor(() => statesOf(a).length > 0 && statesOf(b).length > 0, 'first state broadcasts');

    // Sync: for a tick both clients received, the shared scoreboard
    // view is identical — one authoritative simulation, two observers.
    await waitFor(() => {
      const aTicks = new Map(statesOf(a).map(s => [s.tick, s]));
      return statesOf(b).some(s => aTicks.has(s.tick));
    }, 'a common broadcast tick on both clients');
    const aByTick = new Map(statesOf(a).map(s => [s.tick, s]));
    const shared = statesOf(b).find(s => aByTick.has(s.tick))!;
    assert.deepEqual(
      shared.scoreboard,
      aByTick.get(shared.tick)!.scoreboard,
      'both clients must see the identical scoreboard for the same server tick'
    );
    assert.equal(shared.scoreboard.length, 2, 'the scoreboard must list both players');

    // Server-side movement from inputs only.
    const x0 = statesOf(a).at(-1).you.x;
    let seq = 1;
    const sendInput = setInterval(() => {
      a.ws.send(JSON.stringify({ type: 'input', seq: seq++, left: false, right: true, jump: false }));
    }, 30);
    await waitFor(() => statesOf(a).at(-1).you.x > x0 + 30, 'server-side movement from inputs');
    clearInterval(sendInput);

    // Cheat attempt: a claimed teleport position is ignored by
    // construction — the server simulates, the client only intends.
    const before = statesOf(a).at(-1).you.x;
    a.ws.send(JSON.stringify({ type: 'input', seq: seq++, left: false, right: false, jump: false, x: 99999, y: -500 }));
    await new Promise(r => setTimeout(r, 300));
    const after = statesOf(a).at(-1).you.x;
    assert.ok(after < 2000, `position claim must be ignored (x went ${before} -> ${after}, not 99999)`);
    assert.ok(Math.abs(after - before) < 40, 'a position claim must not move the player at all');

    a.ws.close();
    await waitFor(() => server.stats().clients === 1, 'disconnect cleanup');
    b.ws.close();
  } finally {
    await server.stop();
  }
});
