/**
 * Factory Phase F7 — Games workflow.
 *
 * One described game idea flows through the factory machinery as a
 * single workflow:
 *
 *   description → F5 team by data (GameWorkflow.plan)
 *               → swarm build (the real SwarmOrchestrator chain —
 *                 planner → tasks → parallel workers → sandbox gate →
 *                 verifier → integration → honest verification — over
 *                 a stub transport, the F2–F4 seam)
 *               → F6 environment cycle (GameWorkflow.runEnvironmentCycle:
 *                 the built project opened through the one
 *                 FactoryEnvironment contract, web adapter; build /
 *                 test / preview / export via contract operations only)
 *               → playability verdict (the delivered game.js is
 *                 executed headlessly and played with scripted inputs)
 *
 * The stub is a transport fixture: it stands in for the planner and
 * worker models. The planner's response is the platform's real
 * planner mechanism — create_task actions carrying the game project's
 * file paths — and the worker responses write the platform's own
 * generated game (server/gameEngine GameProjectGenerator, Phase 24),
 * so the tree the chain verifies, the environment exports, and the
 * playability gate executes is the genuine shipped game code. No live
 * model exists in this environment (F1 verdict); this suite proves
 * the workflow machinery, and labels the game content as the
 * platform's own generator output, not live model output.
 *
 * Generated fixture files are this repository's own trusted test
 * content, so the execution adapter may run them on the host.
 */
